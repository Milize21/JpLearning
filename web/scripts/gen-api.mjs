// Generates TypeScript types for every module from the API's OpenAPI documents (docs/05 §14).
// Needs the API running in Development: `dotnet run --project src/Nomax.Api`. Output is committed and never edited by hand.
import { mkdir, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const apiUrl = process.env.NOMAX_API_URL ?? "http://localhost:5080";
// Add a module here when it publishes its OpenAPI document.
const modules = ["identity", "content", "classroom", "practice", "insight"];

await mkdir(new URL("../src/lib/api/schema/", import.meta.url), { recursive: true });

for (const module of modules) {
  const source = new URL(`/openapi/${module}.json`, apiUrl);
  const ast = await openapiTS(source);
  const banner = `/* Generated by \`npm run gen:api\` from /openapi/${module}.json. Do not edit by hand (AGENTS.md §7). */\n\n`;
  await writeFile(new URL(`../src/lib/api/schema/${module}.ts`, import.meta.url), banner + astToString(ast));
  console.log(`generated src/lib/api/schema/${module}.ts`);
}
